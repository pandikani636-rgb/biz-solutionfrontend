export const getSectionsForBrandOrCategory = (brand = 'ALL', category = 'ALL') => {
  if (brand && brand !== 'ALL') {
    const matchedKey = Object.keys(BRAND_SECTIONS_MAP).find(
      (k) => k.toLowerCase() === brand.toLowerCase() || brand.toLowerCase().includes(k.toLowerCase())
    );
    if (matchedKey && BRAND_SECTIONS_MAP[matchedKey]) {
      return BRAND_SECTIONS_MAP[matchedKey];
    }
  }

  if (category && category !== 'ALL') {
    const matchedCatKey = Object.keys(CATEGORY_SECTIONS_MAP).find(
      (k) => k.toLowerCase() === category.toLowerCase() || category.toLowerCase().includes(k.toLowerCase())
    );
    if (matchedCatKey && CATEGORY_SECTIONS_MAP[matchedCatKey]) {
      return CATEGORY_SECTIONS_MAP[matchedCatKey];
    }
  }

  return CATEGORY_SECTIONS_MAP['ALL'];
};

const GENERIC_SECTION_WORDS = new Set(['series', 'bearings', 'belts', 'motors', 'ball', 'roller', 'gear', 'gears', 'units', 'duty', 'industrial']);

export const matchesSectionFilter = (product, section) => {
  if (!section || section === 'ALL' || section === 'All Sections') return true;
  if (!product) return false;
  const sLower = section.toLowerCase().trim();
  const pSec = (product.section || '').toLowerCase().trim();
  const pName = (product.name || '').toLowerCase().trim();
  const pPart = (product.partNumber || '').toLowerCase().trim();
  const pCat = (product.categoryName || '').toLowerCase().trim();

  if (pSec === sLower || pSec.includes(sLower) || sLower.includes(pSec)) return true;
  if (pCat && (pCat === sLower || pCat.includes(sLower) || sLower.includes(pCat))) return true;

  const keywords = sLower
    .replace(/[()&,/-]/g, ' ')
    .split(/\s+/)
    .filter((w) => w.length > 2 && !GENERIC_SECTION_WORDS.has(w));

  if (keywords.length > 0) {
    return keywords.some((k) => pSec.includes(k) || pName.includes(k) || pPart.includes(k));
  }
  return false;
};

export const getProductsForBrand = (brandCodeOrCategory = 'ALL', section = '') => {
  if (!brandCodeOrCategory || brandCodeOrCategory === 'ALL') {
    let combined = [];
    Object.values(OFFICIAL_BRAND_PRODUCTS).forEach((prods) => {
      combined = combined.concat(prods);
    });
    if (section && section !== 'ALL' && section !== 'All Sections') {
      const secFilt = combined.filter((p) => matchesSectionFilter(p, section));
      if (secFilt.length > 0) return secFilt;
    }
    return combined;
  }

  const query = brandCodeOrCategory.toLowerCase().trim();

  // Check if query is a category ID or category name
  const matchedCat = INDUSTRIAL_CATEGORIES.find(
    (c) => c.id.toLowerCase() === query || c.name.toLowerCase().includes(query) || query.includes(c.id.toLowerCase())
  );

  if (matchedCat && matchedCat.id !== 'ALL') {
    let catProds = [];
    matchedCat.brands.forEach((brandCode) => {
      if (OFFICIAL_BRAND_PRODUCTS[brandCode]) {
        catProds = catProds.concat(OFFICIAL_BRAND_PRODUCTS[brandCode]);
      }
    });
    if (catProds.length > 0) {
      if (section && section !== 'ALL' && section !== 'All Sections') {
        const secFilt = catProds.filter((p) => matchesSectionFilter(p, section));
        if (secFilt.length > 0) return secFilt;
      }
      return catProds;
    }
  }

  // Check direct brand match
  const matchedKey = Object.keys(OFFICIAL_BRAND_PRODUCTS).find(
    (k) => k.toLowerCase() === query || query.includes(k.toLowerCase()) || k.toLowerCase().includes(query)
  );

  if (matchedKey && OFFICIAL_BRAND_PRODUCTS[matchedKey]) {
    const brandItems = OFFICIAL_BRAND_PRODUCTS[matchedKey];
    if (section && section !== 'ALL' && section !== 'All Sections') {
      const secFilt = brandItems.filter((p) => matchesSectionFilter(p, section));
      if (secFilt.length > 0) return secFilt;
    }
    return brandItems;
  }

  // Look for partial matches among products
  const matchingProds = [];
  Object.values(OFFICIAL_BRAND_PRODUCTS).forEach((prods) => {
    prods.forEach((p) => {
      if (
        p.brand.toLowerCase().includes(query) ||
        p.categoryName.toLowerCase().includes(query) ||
        p.partNumber.toLowerCase().includes(query)
      ) {
        matchingProds.push(p);
      }
    });
  });

  let finalResults = [];
  if (matchingProds.length > 0) {
    finalResults = matchingProds;
  } else {
    finalResults = [];
  }

  if (section && section !== 'ALL' && section !== 'All Sections') {
    const filtered = finalResults.filter((p) => matchesSectionFilter(p, section));
    if (filtered.length > 0) return filtered;
  }

  return finalResults;
};
