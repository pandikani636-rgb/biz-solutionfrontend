/**
 * Returns all products for a specific brand or all brands combined
 */
export const getProductsForBrand = (brandCodeOrCategory = 'ALL') => {
  if (!brandCodeOrCategory || brandCodeOrCategory === 'ALL') {
    let combined = [];
    Object.values(OFFICIAL_BRAND_PRODUCTS).forEach((prods) => {
      combined = combined.concat(prods);
    });
    return combined;
  }

  const query = brandCodeOrCategory.toLowerCase().trim();

  // Check if query is a category ID or category name
  const matchedCat = INDUSTRIAL_CATEGORIES.find(
    (c) => c.id.toLowerCase() === query || c.name.toLowerCase().includes(query) || query.includes(c.id.toLowerCase())
  );

  if (matchedCat && matchedCat.id !== 'ALL') {
    let catProds = [];
    matchedCat.brands.forEach((brandCode) => {
      if (OFFICIAL_BRAND_PRODUCTS[brandCode]) {
        catProds = catProds.concat(OFFICIAL_BRAND_PRODUCTS[brandCode]);
      }
    });
    if (catProds.length > 0) return catProds;
  }

  // Check direct brand match
  const matchedKey = Object.keys(OFFICIAL_BRAND_PRODUCTS).find(
    (k) => k.toLowerCase() === query || query.includes(k.toLowerCase()) || k.toLowerCase().includes(query)
  );

  if (matchedKey && OFFICIAL_BRAND_PRODUCTS[matchedKey]) {
    return OFFICIAL_BRAND_PRODUCTS[matchedKey];
  }

  // Look for partial matches among products
  const matchingProds = [];
  Object.values(OFFICIAL_BRAND_PRODUCTS).forEach((prods) => {
    prods.forEach((p) => {
      if (
        p.brand.toLowerCase().includes(query) ||
        p.categoryName.toLowerCase().includes(query) ||
        p.partNumber.toLowerCase().includes(query)
      ) {
        matchingProds.push(p);
      }
    });
  });

  if (matchingProds.length > 0) {
    return matchingProds;
  }

  // If no match found, do NOT fallback to PIX! Return empty or combined
  return [];
};
